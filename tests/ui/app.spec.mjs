test('wheel scrolling follows code ranges without feedback, OFF movement or unmapped jumps', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('.code-viewport')).toBeVisible();
  if ((await page.locator('.link-toggle').innerText()).includes('OFF')) await page.locator('.link-toggle').click();
  await page.waitForTimeout(250);
  const code = page.locator('.code-viewport');
  const notes = page.locator('.notes-scroll');
  const toTick = await code.evaluate(el => 20 + 32 * parseFloat(getComputedStyle(el).lineHeight) - Math.min(64, el.clientHeight * .14) - el.scrollTop);
  await code.hover(); await page.mouse.wheel(0, toTick);
  await expect(page.locator('.note-card.active')).toContainText('Tick');
  await page.waitForTimeout(250);
  const before = await code.evaluate(el => el.scrollTop);
  await page.waitForTimeout(350);
  expect(await code.evaluate(el => el.scrollTop)).toBe(before);
  await page.locator('.link-toggle').click();
  const independent = await notes.evaluate(el => el.scrollTop);
  await code.hover(); await page.mouse.wheel(0, -220);
  await page.waitForTimeout(250);
  expect(await notes.evaluate(el => el.scrollTop)).toBe(independent);
  await page.locator('.link-toggle').click();
  await page.waitForTimeout(250);
  const toFirst = await notes.evaluate(el => {
    const first = el.querySelector('[data-note]');
    return first.getBoundingClientRect().top - el.getBoundingClientRect().top - Math.min(64, el.clientHeight * .14) + 8;
  });
  await notes.hover(); await page.mouse.wheel(0, toFirst);
  await expect(page.locator('.note-card.active')).toContainText('생성자');
  await expect(page.locator('.code-line.related').first()).toHaveAttribute('data-line', '7');
  await page.waitForTimeout(250);
  await code.hover(); await page.mouse.wheel(0, 100000);
  await expect(page.locator('.sync-status')).toContainText('현재 위치에 연결된 해설이 없습니다');
  const preserved = await notes.evaluate(el => el.scrollTop);
  await page.mouse.wheel(0, 500);
  await page.waitForTimeout(200);
  expect(await notes.evaluate(el => el.scrollTop)).toBe(preserved);
});

